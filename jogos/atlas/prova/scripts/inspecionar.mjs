// Resumo rápido do cache cru: valores de class/subtype, fontes, nomes etc.
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
const dir = join(process.cwd(), '.cache', process.argv[2] ?? 'urca');
const L = async (n) => JSON.parse(await readFile(join(dir, n + '.json'), 'utf8'));
const cnt = (arr, f) => { const m = {}; for (const x of arr) { const k = f(x); m[k] = (m[k] ?? 0) + 1; } return Object.entries(m).sort((a, b) => b[1] - a[1]); };
const b = await L('buildings_building');
console.log('PRÉDIOS', b.length);
console.log(' geometria', cnt(b, (r) => r.geometry.type));
console.log(' com height', b.filter((r) => r.height != null).length, 'num_floors', b.filter((r) => r.num_floors != null).length, 'ambos', b.filter((r) => r.height != null && r.num_floors != null).length, 'algum', b.filter((r) => r.height != null || r.num_floors != null).length);
console.log(' roof_shape', cnt(b, (r) => r.roof_shape));
console.log(' class', cnt(b, (r) => r.class).slice(0, 15));
console.log(' subtype', cnt(b, (r) => r.subtype));
console.log(' has_parts', cnt(b, (r) => r.has_parts), 'underground', cnt(b, (r) => r.is_underground));
console.log(' fonte(dataset)', cnt(b, (r) => (r.sources ?? []).map((s) => s.dataset).join('+')));
console.log(' licença', cnt(b, (r) => (r.sources ?? []).map((s) => s.license).join('+')));
console.log(' facade_color', cnt(b, (r) => r.facade_color).slice(0, 5), 'roof_color', cnt(b, (r) => r.roof_color).slice(0, 5), 'roof_material', cnt(b, (r) => r.roof_material).slice(0, 5));
console.log(' nomeados', b.filter((r) => r.names?.primary).map((r) => `${r.names.primary} h=${r.height} n=${r.num_floors} cls=${r.class}`).slice(0, 40));
const hs = b.filter((r) => r.height != null).map((r) => r.height).sort((a, b) => a - b);
console.log(' altura p10/50/90/max', [0.1, 0.5, 0.9, 1].map((q) => hs[Math.min(hs.length - 1, Math.floor(q * hs.length))]));
const t = await L('transportation_segment');
console.log('\nRUAS', t.length, cnt(t, (r) => r.subtype), cnt(t, (r) => r.class));
console.log(' nomes', cnt(t.filter((r) => r.names?.primary), (r) => r.names.primary).slice(0, 40));
const w = await L('base_water');
console.log('\nÁGUA', w.length, cnt(w, (r) => r.subtype + '/' + r.class), w.filter((r) => r.names?.primary).map((r) => r.names.primary).slice(0, 10), cnt(w, (r) => r.geometry.type));
const l = await L('base_land');
console.log('\nTERRA', l.length, cnt(l, (r) => r.subtype + '/' + r.class), cnt(l, (r) => r.geometry.type));
console.log(' nomeados', l.filter((r) => r.names?.primary).map((r) => r.names.primary + ':' + r.subtype + '/' + r.class).slice(0, 25));
const u = await L('base_land_use');
console.log('\nUSO', u.length, cnt(u, (r) => r.subtype + '/' + r.class), cnt(u, (r) => r.geometry.type));
console.log(' nomeados', u.filter((r) => r.names?.primary).map((r) => r.names.primary + ':' + r.subtype + '/' + r.class).slice(0, 25));
const i = await L('base_infrastructure');
console.log('\nINFRA', i.length, cnt(i, (r) => r.subtype + '/' + r.class), cnt(i, (r) => r.geometry.type));
console.log(' nomeados', i.filter((r) => r.names?.primary).map((r) => r.names.primary + ':' + r.subtype + '/' + r.class).slice(0, 25));
