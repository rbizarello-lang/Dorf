// Gerador pseudoaleatório determinístico (mulberry32) e utilitários de sorteio.
export type Rng = () => number;

export function mulberry32(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Ruído de lattice sem estado: mesmo (x, y, sal) dá sempre o mesmo valor em [0, 1). */
export function hash2(x: number, y: number, salt: number): number {
  let h = Math.imul(x | 0, 374761393) ^ Math.imul(y | 0, 668265263) ^ Math.imul(salt | 0, 2147483647);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}

export function shuffle<T>(arr: T[], rng: Rng): T[] {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/** Faz as quatro sementes independentes (mapa, achados, baralho, metas) a partir de uma só. */
export function subSeed(seed: number, salt: number): number {
  return (Math.imul(seed >>> 0, 2654435761) ^ Math.imul(salt, 40503) ^ 0x9e3779b9) >>> 0;
}
